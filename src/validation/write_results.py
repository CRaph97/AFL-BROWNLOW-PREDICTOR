"""
Render docs/2027_MODEL_R&D_RESULTS.md from data/experiments/analysis/* and the
metric tables, so the results document is reproducible from the artefacts.
Run after analyze.py and champion.py:  python -m src.validation.write_results
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
AN = ROOT / "data" / "experiments" / "analysis"
MET = ROOT / "data" / "experiments" / "metrics"
DOC = ROOT / "docs" / "2027_MODEL_R&D_RESULTS.md"


def md(df: pd.DataFrame, floatfmt: int = 3) -> str:
    if df.empty:
        return "_(not available)_\n"
    cols = list(df.columns)
    out = "| " + " | ".join(str(c) for c in cols) + " |\n|" + "---|" * len(cols) + "\n"
    for r in df.itertuples(index=False):
        cells = []
        for v in r:
            if isinstance(v, float):
                cells.append("" if pd.isna(v) else f"{v:.{floatfmt}f}")
            else:
                cells.append(str(v))
        out += "| " + " | ".join(cells) + " |\n"
    return out


def _csv(name):
    p = AN / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else pd.DataFrame()


def build() -> str:
    pooled, by = _csv("comparison_pooled"), _csv("comparison_by_season")
    champ, checks = _csv("champion"), _csv("promotion_checks")
    pb, cal, ds, bias, fz = _csv("paired_bootstrap_vs_A"), _csv("calibration_study"), _csv("disagreement_summary"), _csv("bias_study"), _csv("forensic_by_season")
    ens, w = _csv("ensemble_by_season"), _csv("ensemble_weights")
    tune = _csv("ranker_tuning_summary")
    from dashboard.model_lab import ablation_table  # noqa: WPS433 (reuse the same aggregation the page shows)
    try:
        ab = ablation_table.__wrapped__() if hasattr(ablation_table, "__wrapped__") else ablation_table()
    except Exception:  # noqa: BLE001
        ab = pd.DataFrame()
    repro = json.loads((ROOT / "data" / "experiments" / "reproduce_2026_check.json").read_text()) if (ROOT / "data" / "experiments" / "reproduce_2026_check.json").exists() else {}
    feat_man = json.loads((ROOT / "data" / "features" / "build_manifest.json").read_text())
    reg = json.loads((ROOT / "data" / "features" / "feature_registry.json").read_text())

    s = ["# 2027 Brownlow model — R&D results\n", "Generated by `python -m src.validation.write_results` from `data/experiments/`. Plan and rules: `docs/2027_MODEL_R&D_PLAN.md`.\n"]
    findings = AN / "findings.md"
    if findings.exists():
        s.append("## 0. Findings (curated from the tables below)\n"); s.append(findings.read_text() + "\n")
    s.append("## 1. Baseline reproduction\n")
    if repro:
        s.append(f"The new metric code, run on the frozen 2026 Production and Objective match probabilities, gives 3-vote accuracy "
                 f"{repro['production_2026_frozen']['correct_3']:.4f} (frozen evaluation {repro['frozen_2026_evaluation']['Production']['hit_3_rate']:.4f}) and "
                 f"{repro['objective_2026_frozen']['correct_3']:.4f} ({repro['frozen_2026_evaluation']['Objective']['hit_3_rate']:.4f}); reproduced = {repro['reproduced']}. "
                 f"Production's denominator differs by 8 matches because its roster omits some 2/1-vote getters (first-game exclusion), which the new per-match table skips rather than scores.\n")
    base = MET / "baseline_phase4_pl_legacy.csv"
    if base.exists():
        b = pd.read_csv(base); b8 = b[(b["window"] == "recent8") & (b["test_season"].between(2015, 2025))]
        s.append(f"Phase 4 configuration (legacy 68 CORE features, recent-8 window) re-run walk-forward 2015-2025: mean 3-vote accuracy {b8['correct_3'].mean():.4f}, "
                 f"exact 3-2-1 {b8['exact_321'].mean():.4f} (docs/MODEL_BACKTEST.md reported 0.5750 / 0.0913 for the same window; differences come from median vs dropna handling being identical here, "
                 f"but the 2026-extended table's re-normalised round labels and the analytic-gradient optimiser converging further).\n")
    s.append("## 2. Data and features\n")
    s.append(f"Feature store: {feat_man['rows']:,} player-match rows, seasons {feat_man['seasons'][0]}-{feat_man['seasons'][1]}, {feat_man['matches']:,} matches, {feat_man['n_feature_columns']} registered feature columns in {len(reg)} families. "
             "Label sources: " + ", ".join(f"{k} {v:,}" for k, v in feat_man["label_sources"].items()) + ".\n")
    s.append(md(pd.DataFrame([{"family": k, "timing": v["timing"], "n_columns": len(v["columns"])} for k, v in reg.items()])))
    s.append("## 3. Walk-forward comparison (test seasons 2012-2026, expanding window)\n")
    for scope in sorted(pooled["window_seasons"].unique()) if not pooled.empty else []:
        s.append(f"**{scope}**\n")
        s.append(md(pooled[pooled["window_seasons"] == scope][["model", "n_seasons", "n_matches", "correct_3", "a3_in_top3", "exact_321", "log_loss_p3", "brier_p3", "ece_p3", "season_mae", "spearman", "top10_hit"]], 4))
    if not by.empty:
        s.append("**3-vote accuracy by season**\n")
        s.append(md(by.pivot(index="season", columns="model", values="correct_3").reset_index(), 3))
        s.append("**P3 log loss by season**\n")
        s.append(md(by.pivot(index="season", columns="model", values="log_loss_p3").reset_index(), 3))
        s.append("**Season-total MAE by season**\n")
        s.append(md(by.pivot(index="season", columns="model", values="season_mae").reset_index(), 3))
    if not pb.empty:
        s.append("**Paired bootstrap (A minus other; 95% CI over matches)**\n"); s.append(md(pb, 4))
    s.append("## 4. Champion decision\n")
    if not champ.empty:
        s.append(md(champ))
    if not checks.empty:
        s.append(md(checks, 4))
    if not tune.empty:
        s.append("Ranker hyperparameters (inner-holdout PL NLL on pilot folds 2014-2016):\n"); s.append(md(tune, 4))
    s.append("## 5. Ensemble research\n")
    if not ens.empty:
        s.append(md(ens.groupby("model")[["correct_3", "log_loss_p3", "ece_p3", "exact_321", "season_mae", "spearman"]].mean().reset_index(), 4))
        s.append(md(w, 3))
    s.append("## 6. Feature-family ablation (Structural model, recent-8 window, 2017-2026)\n")
    if not ab.empty:
        s.append(md(ab.sort_values("d_correct_3"), 4))
        s.append("Negative `d_correct_3` / positive `d_log_loss` for a `minus_` row means the family helps. `plus_reputation_legacy` uses same-season votes and is NOT deployable.\n")
    s.append("## 7. Calibration\n")
    if not cal.empty:
        s.append(md(cal, 4))
    s.append("## 8. Disagreement as information\n")
    if not ds.empty:
        s.append(md(ds, 3))
    s.append("## 9. Bias and 2026 forensics tested historically\n")
    if not bias.empty:
        s.append("**3-voter hit rate by role (all seasons)**\n")
        s.append(md(bias[(bias["dimension"] == "role") & (bias["scope"] == "all")].pivot(index="group", columns="model", values="hit_rate").reset_index(), 3))
        s.append("**Season EV bias by role (relevant players, recent 2022-2026)**\n")
        s.append(md(bias[(bias["dimension"] == "season_ev_bias_by_role") & (bias["scope"].str.startswith("recent"))].pivot(index="group", columns="model", values="mean_error").reset_index(), 3))
        s.append("**3-voter hit rate by margin bucket and for losing-team 3-voters**\n")
        s.append(md(bias[(bias["dimension"].isin(["margin_bucket", "losing_team_3voter"])) & (bias["scope"] == "all")][["model", "dimension", "group", "n_3voters", "hit_rate"]], 3))
    if not fz.empty:
        s.append("**Ruck EV bias and defender 3-voter hit rate by season (Structural A)**\n")
        f = fz[fz["model"] == "Structural (A)"][["season", "RUCK_ev_bias", "RUCK_n", "MIDFIELDER_3voter_hit", "KEY_DEFENDER_3voter_hit", "KEY_DEFENDER_3voters", "MEDIUM_DEFENDER_3voter_hit", "MEDIUM_DEFENDER_3voters"]]
        s.append(md(f, 3))
    s.append("## 10. Betting research\n")
    s.append("No historical bookmaker prices are held, so betting signals are backtestable only where they depend on model outputs (probability bands, agreement, disagreement, calibration). "
             "The 2026 settled pre-count markets (`data/evaluation/2026`) remain the only priced evidence (one season). See `data/experiments/analysis/betting_research.csv`. "
             "No staking optimisation; no claim of future profitability.\n")
    return "\n".join(s)


if __name__ == "__main__":
    DOC.write_text(build())
    print(f"wrote {DOC}")
